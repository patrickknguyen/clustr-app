/**
 * Build the label vocabulary data-driven from the Unsplash Dataset (Lite).
 *
 * Reads the dataset's `keywords.tsv*` shards, counts how often each keyword is
 * applied across the 25k photos, applies light principled filtering (lowercase,
 * dedupe, drop numerics / platform-meta words / over-long phrases), ranks by
 * frequency, and writes the top-N to `src/lib/vocabulary.ts`.
 *
 * Provenance: "the N most frequent descriptive keywords in the Unsplash Dataset
 * (Lite)" — reproducible, domain-aligned (aesthetic photography = moodboard fuel).
 *
 * Usage: npm run build:vocab -- <extracted-dataset-dir> [N]
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = process.argv[2] ?? '/tmp/unsplash-lite';
const TOP_N = Number(process.argv[3] ?? 2000);
const OUT = 'src/lib/vocabulary.ts';

// Platform / format / usage words that describe the *file*, not the *content*.
const META = new Set([
  'background', 'backgrounds', 'wallpaper', 'wallpapers', 'wallpaper hd', 'hd',
  '4k', 'uhd', 'image', 'images', 'photo', 'photos', 'photography', 'picture',
  'pictures', 'free', 'unsplash', 'download', 'desktop', 'screensaver', 'stock',
  'copy space', 'no person', 'free image', 'free photo', 'free picture',
]);

// Substrings that mark a platform/format meta-tag rather than image content.
const META_SUBSTR = ['background', 'wallpaper', 'screensaver'];
// Latin taxonomic family/genus suffixes emitted by AI taggers (e.g. "asteraceae").
const TAXONOMIC = /(aceae|idae|inae)$/;

const isNumeric = (s: string) => /^[\d.]+$/.test(s);

function loadKeywords(): Map<string, number> {
  const shards = readdirSync(DIR)
    .filter((f) => f.startsWith('keywords.tsv'))
    .sort();
  if (shards.length === 0) throw new Error(`no keywords.tsv* in ${DIR}`);

  // Concatenate shards before splitting — they may be split mid-line.
  let raw = '';
  for (const f of shards) raw += readFileSync(join(DIR, f), 'utf8');

  const counts = new Map<string, number>();
  for (const line of raw.split('\n')) {
    if (!line) continue;
    const kw = (line.split('\t')[1] ?? '').trim().toLowerCase();
    if (!kw || kw === 'keyword') continue; // skip empties + header
    if (kw.length < 3 || isNumeric(kw)) continue;
    if (kw.split(/\s+/).length > 3) continue;
    if (META.has(kw)) continue;
    if (META_SUBSTR.some((m) => kw.includes(m))) continue;
    if (!kw.includes(' ') && TAXONOMIC.test(kw)) continue;
    counts.set(kw, (counts.get(kw) ?? 0) + 1);
  }
  return counts;
}

function main() {
  const counts = loadKeywords();
  const ranked = [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, TOP_N)
    .map(([w]) => w);

  const rows: string[] = [];
  for (let i = 0; i < ranked.length; i += 10) {
    rows.push('  ' + ranked.slice(i, i + 10).map((w) => JSON.stringify(w)).join(', ') + ',');
  }

  const file = `// AUTO-GENERATED by scripts/build-vocab.ts — do not edit by hand.
// The ${ranked.length} most frequent descriptive keywords in the Unsplash Dataset
// (Lite, 25k photos), lowercased and de-duplicated, with numerics, platform/format
// meta-words and over-long phrases removed. Regenerate with: npm run build:vocab.
//
// CLIP is open-vocabulary; this is the candidate set we rank cluster centroids
// against. Labels are embedded as \`a photo of {word}\`.

export const LABEL_TEMPLATE = (word: string) => \`a photo of \${word}\`;

export const VOCABULARY: string[] = [
${rows.join('\n')}
];
`;
  writeFileSync(OUT, file);
  console.log(`wrote ${ranked.length} words to ${OUT} (from ${counts.size} unique keywords)`);
  console.log('top 20:', ranked.slice(0, 20).join(', '));
}

main();
